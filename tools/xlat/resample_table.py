#!/usr/bin/env python3
"""The resampler's filters (rp/src/include/resample_table.h): for each of
the songs' two rates (25,033 Hz for the DMA chip, 7,777 Hz for the YM),
from the renders' 22,050 Hz, a Kaiser-windowed sinc cut at 90% of the lower
rate's Nyquist, in PHASES fractional positions of TAPS taps, each phase's
taps summing to 1 in Q14. Generated once and committed, so that the host and
the RP resample with the same integers.

usage: resample_table.py > rp/src/include/resample_table.h
"""

import math

PHASES = 128
SOURCE = 22050
RATES = {"ST": (25033, 24), "YM": (7777, 48)}
BETA = 8.0


def bessel_i0(x):
    total, term, k = 1.0, 1.0, 1
    while term > 1e-12 * total:
        term *= (x / (2 * k)) ** 2
        total += term
        k += 1
    return total


def phase_taps(cutoff, taps, frac):
    out = []
    for k in range(taps):
        t = k - (taps // 2 - 1) - frac  # the input sample's distance from the output's position
        x = cutoff * t
        sinc = 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)
        w = t / (taps / 2)
        window = bessel_i0(BETA * math.sqrt(max(0.0, 1 - w * w))) / bessel_i0(BETA) if abs(w) <= 1 else 0
        out.append(cutoff * sinc * window)
    total = sum(out)
    q = [round(v / total * 16384) for v in out]
    q[taps // 2 - 1] += 16384 - sum(q)  # each phase sums to exactly 1
    return q


print("/* Generated by tools/xlat/resample_table.py: do not edit. The songs'")
print(" * resampling filters (sound_convert.c), Q14, from 22,050 Hz. */")
print("#ifndef RESAMPLE_TABLE_H\n#define RESAMPLE_TABLE_H\n\n#include <stdint.h>\n")
print(f"#define RESAMPLE_PHASES {PHASES}u")
for name, (rate, taps) in RATES.items():
    cutoff = min(1.0, rate / SOURCE) * 0.9
    print(f"#define RESAMPLE_{name}_RATE {rate}u\n#define RESAMPLE_{name}_TAPS {taps}u")
    print(f"static const int16_t k_resample_{name.lower()}[{PHASES}][{taps}] = {{")
    for p in range(PHASES):
        print("  {" + ", ".join(str(v) for v in phase_taps(cutoff, taps, p / PHASES)) + "},")
    print("};")
print("\n#endif")
