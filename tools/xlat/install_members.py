#!/usr/bin/env python3
"""The members of the Amiga port's repository zip that the RP's install gate
reads (rp/src/include/install_members.h), with each one's size and CRC-32
from the zip's directory: the effects in EFFECTS.SE8's order (the game's
sample table's), the songs' renders, and SZ2.X's hex dump. The gate refuses
a member that differs. Names, sizes and CRCs only: nothing of the game.

usage: install_members.py REPOSITORY.zip > rp/src/include/install_members.h
"""

import sys
import zipfile

EFFECTS = ["BOM1.pcm", "BOM2.PCM", "AJ03_.pcm", "GF01B.PCM", "DG12_.PCM", "MS08_.PCM",
           "FMAKE18.pcm", "THUD.PCM", "GMSE_00A.pcm", "GMSE_011.pcm", "GMSE_008.pcm",
           "GMSE_004.pcm", "GMSE_003.pcm", "GMSE_017.pcm", "DG06.PCM", "SE_04.PCM", "SE_02.PCM",
           "SE_01.PCM", "SE_03.PCM", "SE_06.PCM", "SE_05.PCM", "TO28.PCM", "RECCA3.pcm",
           "RECCA1.pcm", "RAI03_.pcm", "FMAKE33.PCM", "DG03.PCM", "DG04.PCM", "TO12.PCM",
           "MS05_.PCM", "FMAKE32.PCM"]
SONGS = ["SZ2_B1", "SZ2_B2", "SZ2_B3", "SZ2_NM", "SZ2_S0", "SZ2_S1", "SZ2_S2", "SZ2_S3", "SZ2_S4",
         "SZ2_S5", "SZ2_S6", "SZ2_TMP"]

z = zipfile.ZipFile(sys.argv[1])
by_path = {}
for info in z.infolist():
    path = info.filename.split("/", 1)[1] if "/" in info.filename else info.filename
    by_path[path] = info


def row(path):
    info = by_path[path]
    return f'  {{"{path}", {info.file_size}u, 0x{info.CRC:08X}u}},'


print("/* Generated by tools/xlat/install_members.py from the Amiga port's repository")
print(f" * zip ({z.comment.decode(errors='replace')}): do not edit. */")
print("#ifndef INSTALL_MEMBERS_H\n#define INSTALL_MEMBERS_H\n\n#include <stdint.h>\n")
print("typedef struct {\n  const char *path;\n  uint32_t size, crc;\n} install_member_t;\n")
print('#define INSTALL_REPOSITORY_COMMIT "' + z.comment.decode() + '"')
print('#define INSTALL_PROGRAM_PATH "binaries/x68000/sz2.hex"')
print("static const install_member_t k_install_program = " + row("binaries/x68000/sz2.hex")[2:-1] + ";")
print(f"#define INSTALL_EFFECTS {len(EFFECTS)}u")
print("static const install_member_t k_install_effects[INSTALL_EFFECTS] = {")
for name in EFFECTS:
    print(row("binaries/amiga/PCM_DAT/" + name))
print("};")
print(f"#define INSTALL_SONGS {len(SONGS)}u")
print("static const install_member_t k_install_songs[INSTALL_SONGS] = {")
for name in SONGS:
    print(row(f"binaries/amiga/MUSIC_DAT/{name}.crm"))
print("};\n\n#endif")
